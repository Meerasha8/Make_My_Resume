-- Supabase schema for Make My Resume
-- Paste this into the Supabase SQL editor and run it.
-- Fixed: CREATE POLICY does not support IF NOT EXISTS in Postgres,
-- so each policy is now DROP-then-CREATE to stay idempotent/rerunnable.

create extension if not exists vector;
create extension if not exists pgcrypto;

-- Profiles table (optional but recommended for auth integration)
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null,
    email text not null,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile" on public.profiles
    for select using (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles
    for update using (auth.uid() = id) with check (auth.uid() = id);

-- Trigger-based profile creation for auth.users rows.
-- This avoids direct inserts from the app backend and keeps RLS enabled.
drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.handle_new_user();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, username, email)
    values (
        new.id,
        new.raw_user_meta_data ->> 'username',
        new.email
    )
    on conflict (id) do update
        set username = excluded.username,
            email = excluded.email,
            updated_at = now();

    return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();

-- User details
create table if not exists public.user_details (
    id bigint generated by default as identity primary key,
    name text,
    mobile_number text,
    email_id text,
    github_url text,
    linkedin_url text,
    portfolio_link text,
    location text,
    profession_summary text,
    user_uuid uuid not null references auth.users(id) on delete cascade,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create unique index if not exists idx_user_details_user_uuid_unique on public.user_details(user_uuid);

alter table public.user_details enable row level security;

drop policy if exists "Users can manage own user details" on public.user_details;
create policy "Users can manage own user details" on public.user_details
    for all using (auth.uid() = user_uuid) with check (auth.uid() = user_uuid);

